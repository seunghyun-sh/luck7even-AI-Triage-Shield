def get_triage_prompt(url, parameter, payload, response_body):
    return f"""
    너는 최고 수준의 웹 보안 분석가다. 아래의 1차 탐지 결과를 분석하라.
    
    [탐지 정보]
    - URL: {url}
    - 파라미터: {parameter}
    - 주입한 페이로드: {payload}
    
    [응답 본문(HTML/Error)]
    {response_body}
    
    [핵심 지시사항]
    1. 주입한 페이로드가 필터링(인코딩) 없이 그대로 실행 가능한 상태인지, 아니면 안전하게 방어되었는지 판단해라.
    2. 응답 본문이 영어로 되어 있더라도, 반드시 모든 분석 결과와 설명은 100% 한국어로만 작성해라.
    3. XSS 진단 시: 응답 본문에 페이로드가 존재하더라도 꺾쇠 기호(`<`, `>`)가 HTML Entity(`&lt;`, `&gt;`)로 안전하게 치환(인코딩)되어 있다면 스크립트가 실행될 수 없으므로 반드시 '양호'로 판정해라.

    위 응답 본문을 보고, 주입한 페이로드가 필터링(인코딩) 없이 그대로 실행 가능한 상태인지, 
    아니면 안전하게 방어되었는지 판단하여 결과를 JSON으로 반환하라.
    """